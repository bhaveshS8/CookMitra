// Render a customer name in Devanagari for cook-facing messages.
// Already-Devanagari names pass through unchanged; initials stay initials.
const toDevanagariName = (value) => {
  const text = String(value ?? "").trim();
  if (!text) return "";
  return text.replace(/[A-Za-z]+|[^A-Za-z]+/g, (chunk) => {
    if (!/^[A-Za-z]+$/.test(chunk)) return chunk;
    const key = chunk.toLowerCase();
    if (NAME_MAP[key]) return NAME_MAP[key];
    return transliterateNameWord(chunk);
  });
};

module.exports = { toDevanagariName, NAME_MAP };
